-- Banco B: championship configuration. This table stores configuration only;
-- it does not alter or delete any existing game records.
create table if not exists public.championship_configs (
  id bigint generated by default as identity primary key,
  campeonato text not null,
  temporada text not null,
  total_rodadas integer null check (total_rodadas is null or total_rodadas > 0),
  pontos_vitoria numeric not null default 3,
  pontos_empate numeric not null default 1,
  pontos_derrota numeric not null default 0,
  criterios_desempate jsonb not null default '["goalDifference","goalsFor","wins"]'::jsonb,
  janela_jogos integer null check (janela_jogos is null or janela_jogos > 0),
  contexto text not null default 'GERAL' check (contexto in ('GERAL','CASA','VISITANTE')),
  updated_at timestamptz not null default now(),
  unique (campeonato, temporada)
);
